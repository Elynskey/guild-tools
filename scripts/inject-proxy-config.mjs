// Build-time step: bakes the API proxy's connection details into the packaged app.
// Reads .env.proxy (gitignored, local-machine-only -- see electron/dataSources/
// proxyConfig.cjs for why these three values, and only these three, are the
// exception to "secrets never ship in the installer") and writes
// electron/proxyConfig.generated.cjs, which DOES get bundled (electron/**/* is part
// of the electron-builder file glob).
//
// If .env.proxy is missing, this is a no-op -- the packaged build just won't have
// proxy mode available, falling back to sample data like it always has. Not an error:
// most local builds (this developer's own machine, testing something unrelated)
// don't need proxy mode wired up.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import dotenv from 'dotenv';

const ROOT = path.resolve(import.meta.dirname, '..');
const SOURCE = path.join(ROOT, '.env.proxy');
const OUT = path.join(ROOT, 'electron', 'dataSources', 'proxyConfig.generated.cjs');

const REQUIRED_KEYS = ['PROXY_BASE_URL', 'PROXY_API_KEY', 'BNET_CLIENT_ID'];
// Discord sign-in is currently paused (see plan notes) -- optional so builds don't
// need a value for a feature that isn't shipped/wired into the UI yet.
const OPTIONAL_KEYS = ['DISCORD_CLIENT_ID'];

function main() {
  if (!existsSync(SOURCE)) {
    console.log('[inject-proxy-config] No .env.proxy found -- skipping (proxy mode unavailable in this build).');
    return;
  }

  const parsed = dotenv.parse(readFileSync(SOURCE, 'utf8'));
  const missing = REQUIRED_KEYS.filter((k) => !parsed[k]);
  if (missing.length > 0) {
    throw new Error(`[inject-proxy-config] .env.proxy is missing: ${missing.join(', ')}`);
  }

  const keys = [...REQUIRED_KEYS, ...OPTIONAL_KEYS.filter((k) => parsed[k])];
  const body = `// GENERATED by scripts/inject-proxy-config.mjs from .env.proxy -- do not edit by hand.\nmodule.exports = ${JSON.stringify(Object.fromEntries(keys.map((k) => [k, parsed[k]])), null, 2)};\n`;
  writeFileSync(OUT, body);
  console.log(`[inject-proxy-config] Wrote ${path.relative(ROOT, OUT)}.`);
}

main();
